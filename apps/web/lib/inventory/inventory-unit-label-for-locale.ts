function normalizeUnitToken(value: string): string {
  return value.trim().toLowerCase().replace(/\s+/g, " ");
}

function unitKeyForToken(value: string): UnitKey | null {
  const key = normalizeUnitToken(value);
  if (!key) return null;
  return ALIAS_TO_KEY[key] ?? null;
}

/**
 * Lagereinheit für eine Nachricht.
 * Deutsch nutzt dieselben Wörter wie die Bestandsliste.
 * Unbekannte eigene Namen bleiben unverändert.
 */
export function localizeInventoryUnitLabel(
  raw: string,
  locale: string | null | undefined,
): string {
  const value = raw.trim();
  if (!value) return "";
  const loc = normalizeAppLocale(locale);
  if (loc === "de") return inventoryUnitLabelDe(value, value);
  const key = unitKeyForToken(value);
  if (!key) return value;
  return UNIT_LABELS[loc][key];
}

/**
 * Empfänger-Sprache, sonst Sprache des Restaurants, sonst Deutsch.
 */
export function resolveInventoryNotificationLocale(
  recipientLocale: string | null | undefined,
  restaurantLocale: string | null | undefined,
): AppLocale {
  if (recipientLocale?.trim()) return normalizeAppLocale(recipientLocale);
  if (restaurantLocale?.trim()) return normalizeAppLocale(restaurantLocale);
  return DEFAULT_APP_LOCALE;
}
